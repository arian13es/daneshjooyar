/**
 * Checks if the user query is a conversational / chit-chat message.
 * Returns a rich, varied, personalized Persian response or null if it's an informational query.
 */
export function getConversationalReply(rawQuery: string, userName?: string): string | null {
  if (!rawQuery) return null;
  const norm = normalizeAssistantText(rawQuery);
  if (!norm) return null;

  const displayName = userName?.trim() ? `${userName.trim()}` : "دانشجوی عزیز";

  // Check each rule in priority order
  for (const rule of CHIT_CHAT_RULES) {
    for (const pattern of rule.patterns) {
      const normPattern = normalizeAssistantText(pattern);
      if (!normPattern) continue;

      const isExact = norm === normPattern;
      const startsWith = norm.startsWith(normPattern + " ");
      const endsWith = norm.endsWith(" " + normPattern);
      const isSub = norm.includes(" " + normPattern + " ");

      if (isExact || startsWith || endsWith || isSub) {
        const pool = rule.replies(displayName);
        // Deterministic pseudo-random selection based on string length and first char
        const hash = norm.length + (norm.charCodeAt(0) || 0) + (norm.charCodeAt(norm.length - 1) || 0);
        const index = hash % pool.length;
        return pool[index];
      }
    }
  }

  return null;
}
